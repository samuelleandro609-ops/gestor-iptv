-- Gestor Flex (versão externa) — saldo decimal de créditos + indicação de contas.
-- Dialeto: Postgres. Idempotente (ALTER TYPE para o mesmo tipo com
-- USING, ADD COLUMN IF NOT EXISTS, CREATE TABLE/INDEX IF NOT EXISTS):
-- rodar de novo não apaga dados nem dá erro. Cada instrução é uma
-- única sentença, sem blocos internos — o executor divide o arquivo
-- em ";\n" e roda uma sentença por vez.
-- Saldo decimal: a API do painel não informa o saldo de créditos do
-- revendedor, então o gestor acompanha o saldo localmente; valores
-- fracionários (ex.: 4,53, ou 0,5 crédito de um plano de 15 dias)
-- precisam de double precision, não de integer.
ALTER TABLE servers ALTER COLUMN credits_balance TYPE double precision USING credits_balance::double precision;
ALTER TABLE server_credit_logs ALTER COLUMN delta TYPE double precision USING delta::double precision;
ALTER TABLE server_credit_logs ALTER COLUMN balance_after TYPE double precision USING balance_after::double precision;
ALTER TABLE servers ADD COLUMN IF NOT EXISTS credits_balance_updated_at timestamp(3);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS referral_code text;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS referred_by_account_id integer;
ALTER TABLE settings ADD COLUMN IF NOT EXISTS referral_reward_days integer NOT NULL DEFAULT 30;
CREATE TABLE IF NOT EXISTS referral_rewards (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  referrer_account_id integer NOT NULL,
  referred_account_id integer NOT NULL,
  subscription_payment_id integer NOT NULL,
  days_granted integer NOT NULL,
  granted_at timestamp(3) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS referral_rewards_referred_uidx ON referral_rewards (referred_account_id);
CREATE UNIQUE INDEX IF NOT EXISTS referral_rewards_payment_uidx ON referral_rewards (subscription_payment_id);
CREATE UNIQUE INDEX IF NOT EXISTS accounts_referral_code_uidx ON accounts (referral_code) WHERE referral_code IS NOT NULL;
UPDATE accounts SET referral_code = upper(substr(md5(random()::text), 1, 8)) WHERE referral_code IS NULL;
