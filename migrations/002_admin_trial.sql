-- Gestor IPTV (versão externa) — administração, teste grátis e assinatura.
-- Dialeto: Postgres. Idempotente (ADD COLUMN IF NOT EXISTS / CREATE
-- TABLE IF NOT EXISTS): rodar de novo não apaga dados. Nenhum dado é
-- apagado por esta migração: o bloqueio de conta vencida é só de
-- acesso à interface — clientes, servidores, planos e cobranças
-- permanecem intactos e voltam ao pagar.

-- Contas: papel (admin/user), fim do teste grátis de 5 dias,
-- vencimento da assinatura, valor da assinatura da conta e status.
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS role text NOT NULL DEFAULT 'user';
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS trial_ends_at timestamp(3);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS sub_expires_at timestamp(3);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS sub_price_cents integer NOT NULL DEFAULT 0;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS sub_status text NOT NULL DEFAULT 'trial';
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS last_login_at timestamp(3);

-- Backfill: a conta de menor id é a da dona (criada primeiro no
-- deploy) e vira administradora. As demais contas existentes ganham
-- teste de 5 dias contados da migração. Contas novas ganham o teste
-- no registro (created_at + 5 dias), no código.
UPDATE accounts SET role = 'admin', sub_status = 'active' WHERE id = (SELECT MIN(id) FROM accounts);
UPDATE accounts
  SET trial_ends_at = statement_timestamp() + interval '5 days'
  WHERE role <> 'admin' AND trial_ends_at IS NULL;

-- Tokens de redefinição de senha: guarda só o HASH do token (sha256),
-- nunca o token em si. Uso único (used) e validade de 1 hora.
CREATE TABLE IF NOT EXISTS password_resets (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  account_id integer NOT NULL,
  token_hash text NOT NULL,
  expires_at timestamp(3) NOT NULL,
  used integer NOT NULL DEFAULT 0,
  created_at timestamp(3) NOT NULL DEFAULT now()
);

-- Pagamentos da assinatura do gestor (30 dias por pagamento
-- aprovado). Não tem relação com as cobranças Pix dos clientes IPTV
-- (tabela payments): aqui quem paga é a conta que usa o gestor, com
-- as credenciais de Mercado Pago da conta administradora.
CREATE TABLE IF NOT EXISTS subscription_payments (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  account_id integer NOT NULL,
  mp_payment_id text,
  amount_cents integer NOT NULL,
  status text NOT NULL DEFAULT 'pendente',
  created_at timestamp(3) NOT NULL DEFAULT now(),
  paid_at timestamp(3)
);

