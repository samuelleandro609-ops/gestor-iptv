-- 007: registro dos avisos automáticos de vencimento (scheduler 07h-09h).
-- Uma linha por cliente + tipo + dia (data de São Paulo): é ela que
-- garante "uma vez por dia" mesmo com reinício do servidor ou com o
-- plano gratuito dormindo e acordando. Só linhas com status 'enviado'
-- contam para a unicidade (índice parcial): uma falha libera a vaga
-- para a próxima tentativa no mesmo dia, sem duplicar envio.
CREATE TABLE IF NOT EXISTS warning_sends (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  owner_id integer NOT NULL DEFAULT 0,
  client_id integer NOT NULL,
  kind text NOT NULL,
  sent_date text NOT NULL,
  sent_at timestamp(3),
  status text NOT NULL DEFAULT 'enviado',
  detail text NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX IF NOT EXISTS warning_sends_once_per_day_idx
  ON warning_sends (owner_id, client_id, kind, sent_date)
  WHERE status = 'enviado';
CREATE INDEX IF NOT EXISTS warning_sends_owner_idx ON warning_sends (owner_id, sent_date);
