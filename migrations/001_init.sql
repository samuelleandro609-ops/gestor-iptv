CREATE TABLE IF NOT EXISTS integrations (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  owner_id integer NOT NULL DEFAULT 0,
  provider text NOT NULL DEFAULT 'wplay',
  name text NOT NULL,
  url text NOT NULL,
  panel_user text NOT NULL,
  panel_pass text NOT NULL,
  status text NOT NULL DEFAULT 'nao_testado',
  test_detail text NOT NULL DEFAULT '',
  tested_at bigint,
  panel_info text NOT NULL DEFAULT '',
  sync_detail text NOT NULL DEFAULT '',
  synced_at bigint,
  created_at timestamp(3) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS server_credit_logs (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  owner_id integer NOT NULL DEFAULT 0,
  server_id integer NOT NULL,
  delta integer NOT NULL,
  balance_after integer NOT NULL,
